import Foundation

/// Extract the Swift code blocks from the documentation so the compiler can check them.
///
/// Every ```swift block in the DocC catalog, README.md, and the `///` doc comments of the
/// public library sources becomes the body of its own `async throws` function in
/// `Tests/DocSnippetsTests/DocSnippets.generated.swift`. Building the `DocSnippetsTests`
/// target then fails whenever a documented example no longer matches the API.
/// `#sourceLocation` points compiler errors back at the Markdown.
///
/// Names the examples use without declaring them (`client`, `settings`, ...) come from
/// `Tests/DocSnippetsTests/Prelude.swift`.
///
/// Directives, written as an HTML comment on the line directly above a code fence
/// (DocC and GitHub both hide HTML comments):
///
///     <!-- snippet:skip -->      don't compile this block (1.x code, deliberate errors)
///     <!-- snippet:continue -->  append this block to the previous one in the same file,
///                                so it can use the names that block declared
///     <!-- snippet:toplevel -->  declare the block's types and functions alongside the file's
///                                snippets instead of inside one (each Markdown file gets its
///                                own namespace, so names don't collide across files)
public enum DocSnippets {
    public static let usage = "usage: generate-doc-snippets [--root DIR]   (default: the repository that contains the current directory)"
    public static let output = "Tests/DocSnippetsTests/DocSnippets.generated.swift"

    public enum Directive: String, Sendable {
        case skip, `continue`, toplevel
    }

    public struct Block: Equatable, Sendable {
        public var directive: Directive?
        /// The 1-based line number of the first body line.
        public var line: Int
        public var body: [String]

        public init(directive: Directive?, line: Int, body: [String]) {
            self.directive = directive
            self.line = line
            self.body = body
        }
    }

    /// The files whose Swift blocks are compiled, in a fixed order.
    public static func sources(in root: URL) -> [URL] {
        Files.files(under: root.appendingPathComponent("Sources/KurrentDB/KurrentDB.docc"), suffix: ".md")
            + [root.appendingPathComponent("README.md")]
            + Files.files(under: root.appendingPathComponent("Sources/KurrentDB"), suffix: ".swift")
            + Files.files(under: root.appendingPathComponent("Sources/KurrentDBPool"), suffix: ".swift")
    }

    /// The ```swift blocks of `text`. For a Swift source only the `///` comment text is read;
    /// code lines are blanked so line numbers still match. `path` names the file in errors.
    public static func extract(_ text: String, isSwiftSource: Bool, path: String) throws(ToolError) -> [Block] {
        var lines = Text.lines(of: text)
        if isSwiftSource {
            lines = lines.map(docCommentText)
        }
        var blocks: [Block] = []
        var index = 0
        while index < lines.count {
            guard let indent = fenceIndent(lines[index]) else {
                index += 1
                continue
            }
            var previous = index - 1
            while previous >= 0, lines[previous].allSatisfy(\.isWhitespace) {
                previous -= 1
            }
            let directive = previous >= 0 ? self.directive(of: lines[previous]) : nil
            let fenceLine = index + 1
            index += 1
            var body: [String] = []
            while index < lines.count, !isClosingFence(lines[index]) {
                body.append(dedent(lines[index], by: indent))
                index += 1
            }
            guard index < lines.count else {
                throw ToolError(message: "\(path):\(fenceLine): unterminated ```swift block")
            }
            blocks.append(Block(directive: directive, line: fenceLine + 1, body: body))
            index += 1
        }
        return blocks
    }

    /// The generated file's text and the number of snippet functions in it.
    public static func generate(root: URL) throws(ToolError) -> (text: String, count: Int) {
        var out = [
            "// Generated by scripts/generate-doc-snippets — do not edit.",
            "import Foundation",
            "import KurrentDB",
            "import KurrentDBPool",
            "",
        ]
        var count = 0
        for path in sources(in: root) {
            let relative = Files.relativePath(of: path, to: root)
            // Each Markdown file gets its own namespace, so type names declared in one
            // article don't collide with the same names in another.
            let namespace = "Doc_" + identifier(droppingExtension(relative))
            let text: String
            do {
                text = try String(contentsOf: path, encoding: .utf8)
            } catch {
                throw ToolError(message: "\(relative): \(error)")
            }
            let blocks = try extract(text, isSwiftSource: path.pathExtension == "swift", path: relative)
            var toplevel: [String] = []
            var functions: [[String]] = []
            var current: Int?
            for (index, block) in blocks.enumerated() {
                if block.directive == .skip { continue }
                var code = [location(of: path, line: block.line)] + block.body.map { isImport($0) ? "" : $0 }
                if block.directive == .toplevel {
                    code = code.map(staticDeclaration)
                    toplevel += code + ["#sourceLocation()"]
                    current = nil
                } else if block.directive == .continue, let current {
                    functions[current] += code
                } else {
                    functions.append(["static func snippet\(index)() async throws {"] + code)
                    current = functions.count - 1
                }
            }
            if toplevel.isEmpty, functions.isEmpty { continue }
            count += functions.count
            out.append("enum \(namespace) {")
            out += toplevel
            for function in functions {
                out += function + ["#sourceLocation()", "}"]
            }
            out += ["}", ""]
        }
        return (out.joined(separator: "\n"), count)
    }

    public static func run(_ arguments: [String]) throws(ToolError) -> String {
        let arguments = try Arguments(arguments, usage: usage, options: ["root"])
        _ = try arguments.positional(count: 0)
        let root: URL
        if let path = arguments.value("root") {
            root = Files.realPath(URL(fileURLWithPath: path))
        } else {
            root = try Git.topLevel(of: URL(fileURLWithPath: FileManager.default.currentDirectoryPath))
        }
        let generated = try generate(root: root)
        do {
            try generated.text.write(to: root.appendingPathComponent(output), atomically: true, encoding: .utf8)
        } catch {
            throw ToolError(message: "cannot write \(output): \(error)")
        }
        return "wrote \(generated.count) snippets to \(output)"
    }

    // MARK: Lines

    /// The indentation width of a ```swift fence line, or nil for any other line.
    static func fenceIndent(_ line: String) -> Int? {
        let indent = line.prefix { $0.isWhitespace }
        let rest = line.dropFirst(indent.count)
        guard rest.hasPrefix("```swift"), rest.dropFirst("```swift".count).allSatisfy(\.isWhitespace) else { return nil }
        return indent.count
    }

    static func isClosingFence(_ line: String) -> Bool {
        line.trimmingCharacters(in: .whitespacesAndNewlines) == "```"
    }

    static func directive(of line: String) -> Directive? {
        let comment = line.trimmingCharacters(in: .whitespacesAndNewlines)
        guard comment.hasPrefix("<!--"), comment.hasSuffix("-->"), comment.count >= 7 else { return nil }
        let inner = comment.dropFirst(4).dropLast(3).trimmingCharacters(in: .whitespacesAndNewlines)
        guard inner.hasPrefix("snippet:") else { return nil }
        return Directive(rawValue: String(inner.dropFirst("snippet:".count)))
    }

    /// The text of a `///` line (without one leading space), or "" for a code line.
    static func docCommentText(_ line: String) -> String {
        let rest = line.drop { $0.isWhitespace }
        guard rest.hasPrefix("///") else { return "" }
        let text = rest.dropFirst(3)
        return String(text.hasPrefix(" ") ? text.dropFirst() : text)
    }

    /// Removes the fence's indentation when the line starts with that much whitespace.
    static func dedent(_ line: String, by indent: Int) -> String {
        let prefix = line.prefix(indent)
        guard !prefix.isEmpty, prefix.allSatisfy(\.isWhitespace) else { return line }
        return String(line.dropFirst(indent))
    }

    /// `import Module` on its own: blanked, since the generated file imports what it needs.
    static func isImport(_ line: String) -> Bool {
        let words = line.split(whereSeparator: \.isWhitespace)
        return words.count == 2 && words[0] == "import" && words[1].allSatisfy(isWordCharacter)
    }

    /// Free functions and globals in a toplevel block become static members of the namespace.
    static func staticDeclaration(_ line: String) -> String {
        for keyword in ["func ", "let ", "var "] where line.hasPrefix(keyword) {
            return "static " + line
        }
        return line
    }

    // MARK: Names

    /// Absolute, so diagnostics resolve no matter which directory the compiler runs in.
    static func location(of path: URL, line: Int) -> String {
        "#sourceLocation(file: \"\(path.path)\", line: \(line))"
    }

    /// Runs of non-word characters become one underscore.
    static func identifier(_ text: String) -> String {
        var result = ""
        var inRun = false
        for character in text {
            if isWordCharacter(character) {
                result.append(character)
                inRun = false
            } else if !inRun {
                result.append("_")
                inRun = true
            }
        }
        return result
    }

    /// The path without the last component's extension.
    static func droppingExtension(_ path: String) -> String {
        guard let slash = path.lastIndex(of: "/") else { return droppingExtension(name: path) }
        return String(path[...slash]) + droppingExtension(name: String(path[path.index(after: slash)...]))
    }

    private static func droppingExtension(name: String) -> String {
        guard let dot = name.lastIndex(of: "."), dot != name.startIndex else { return name }
        return String(name[..<dot])
    }

    private static func isWordCharacter(_ character: Character) -> Bool {
        character.isLetter || character.isNumber || character == "_"
    }
}
