import Testing
@testable import Tooling

@Suite struct DocSnippetsTests {
    @Test func extractsBlocksWithTheirDirectivesAndLineNumbers() throws {
        let text = """
        Intro

        ```swift
        let a = 1
        ```

        <!-- snippet:continue -->

        ```swift
        print(a)
        ```
          <!--snippet:skip-->
          ```swift   
          old()
            nested()
         short
          ```
        ```python
        not swift
        ```
        """
        let blocks = try DocSnippets.extract(text, isSwiftSource: false, path: "x.md")
        #expect(blocks == [
            DocSnippets.Block(directive: nil, line: 4, body: ["let a = 1"]),
            DocSnippets.Block(directive: .continue, line: 10, body: ["print(a)"]),
            DocSnippets.Block(directive: .skip, line: 14, body: ["old()", "  nested()", " short"]),
        ])
    }

    @Test func readsOnlyDocCommentsOfSwiftSources() throws {
        let text = """
        /// Use it like this:
        ///
        /// ```swift
        /// let client = KurrentDBClient(settings: settings)
        ///```
        /// Code that mentions ```swift fences in a comment line
        public func f() {}
        """
        let blocks = try DocSnippets.extract(text, isSwiftSource: true, path: "A.swift")
        #expect(blocks == [DocSnippets.Block(directive: nil, line: 4, body: ["let client = KurrentDBClient(settings: settings)"])])
    }

    @Test func unterminatedBlockIsAnError() {
        let error = failure { try DocSnippets.extract("a\n```swift\nlet x = 1\n", isSwiftSource: false, path: "doc.md") }
        #expect(error == ToolError(message: "doc.md:2: unterminated ```swift block"))
    }

    @Test func generatesOneNamespacePerFile() throws {
        let root = TemporaryDirectory()
        root.write("README.md", "```swift\nimport KurrentDB\nlet a = 1\n```\n<!-- snippet:continue -->\n```swift\nprint(a)\n```\n")
        root.write("Sources/KurrentDB/KurrentDB.docc/Articles/Reading events.md", """
        <!-- snippet:toplevel -->
        ```swift
        struct OrderPlaced: Codable {}
        func helper() {}
        ```
        <!-- snippet:skip -->
        ```swift
        broken(
        ```
        ```swift
        helper()
        ```

        """)
        root.write("Sources/KurrentDB/A.swift", "/// ```swift\n/// let x = 1\n/// ```\npublic let x = 1\n")
        root.write("Sources/KurrentDB/Streams.swift", "public let y = 2\n")
        root.write("Sources/KurrentDBPool/Pool.swift", "/// ```swift\n/// await pool()\n/// ```\n")
        let rootPath = Files.realPath(root.url).path
        let generated = try DocSnippets.generate(root: Files.realPath(root.url))
        #expect(generated.count == 4)
        #expect(generated.text == """
        // Generated by scripts/generate-doc-snippets — do not edit.
        import Foundation
        import KurrentDB
        import KurrentDBPool

        enum Doc_Sources_KurrentDB_KurrentDB_docc_Articles_Reading_events {
        #sourceLocation(file: "\(rootPath)/Sources/KurrentDB/KurrentDB.docc/Articles/Reading events.md", line: 3)
        struct OrderPlaced: Codable {}
        static func helper() {}
        #sourceLocation()
        static func snippet2() async throws {
        #sourceLocation(file: "\(rootPath)/Sources/KurrentDB/KurrentDB.docc/Articles/Reading events.md", line: 11)
        helper()
        #sourceLocation()
        }
        }

        enum Doc_README {
        static func snippet0() async throws {
        #sourceLocation(file: "\(rootPath)/README.md", line: 2)

        let a = 1
        #sourceLocation(file: "\(rootPath)/README.md", line: 7)
        print(a)
        #sourceLocation()
        }
        }

        enum Doc_Sources_KurrentDB_A {
        static func snippet0() async throws {
        #sourceLocation(file: "\(rootPath)/Sources/KurrentDB/A.swift", line: 2)
        let x = 1
        #sourceLocation()
        }
        }

        enum Doc_Sources_KurrentDBPool_Pool {
        static func snippet0() async throws {
        #sourceLocation(file: "\(rootPath)/Sources/KurrentDBPool/Pool.swift", line: 2)
        await pool()
        #sourceLocation()
        }
        }

        """)
    }

    @Test func runWritesTheGeneratedFile() throws {
        let root = TemporaryDirectory()
        root.write("README.md", "```swift\nlet a = 1\n```\n")
        root.write("Tests/DocSnippetsTests/.keep", "")
        #expect(try DocSnippets.run(["--root", root.url.path]) == "wrote 1 snippets to Tests/DocSnippetsTests/DocSnippets.generated.swift")
        #expect(root.read("Tests/DocSnippetsTests/DocSnippets.generated.swift").contains("enum Doc_README {"))
    }
}
